#!/usr/bin/env sh
# Деплой на сервере: пересобрать образ, перезапустить приложение и убрать то,
# что сборка оставила на диске. Запуск из корня репозитория: ./deploy.sh
#
# Набор compose-файлов и VITE_API_URL docker compose берёт из корневого .env
# (COMPOSE_FILE, VITE_API_URL) — скрипт их не задаёт.
set -eu

docker compose build
docker compose up -d --remove-orphans

# Диск на сервере маленький, а каждая пересборка оставляет прежний образ без тега
# и кэш слоёв (сотни МБ за раз). Работающие контейнеры и их образы prune не трогает.
# Чистка общая для всего Docker на машине — на сервере, выделенном под магазин,
# это то, что нужно; на рабочей машине скрипт запускать незачем.
docker image prune -f
docker builder prune -f

docker system df
